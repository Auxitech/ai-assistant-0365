using System.Net.Http.Headers;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace MailRouter.Web.Services;

/// <summary>Thin wrapper over the Microsoft Graph REST API (only the calls this app needs).</summary>
public class GraphClient(HttpClient http, GraphAuthService auth, ILogger<GraphClient> log)
{
    private const string Base = "https://graph.microsoft.com/v1.0";

    // ---------- Models ----------
    public record Me(string Id, string Mail, string DisplayName);

    public record MailMessage(
        string Id, string? ConversationId, string Subject, string FromName, string FromAddress,
        string BodyText, DateTimeOffset Received, bool IsAutoGenerated);

    public record ChatInfo(string Id, string ChatType, DateTimeOffset LastUpdated, Dictionary<string, (string Name, string Email)> Members);

    public record ChatMessage(string Id, string ChatId, string FromUserId, string FromName, string BodyText, DateTimeOffset Created);

    // ---------- Me ----------
    public async Task<Me> GetMeAsync(CancellationToken ct)
    {
        var j = await GetAsync($"{Base}/me?$select=id,mail,userPrincipalName,displayName", ct);
        return new Me(j["id"]!.GetValue<string>(),
            (j["mail"]?.GetValue<string>() ?? j["userPrincipalName"]!.GetValue<string>()).ToLowerInvariant(),
            j["displayName"]?.GetValue<string>() ?? "");
    }

    // ---------- Mail ----------
    public async Task<List<MailMessage>> GetInboxSinceAsync(DateTimeOffset since, CancellationToken ct)
    {
        var filter = Uri.EscapeDataString($"receivedDateTime gt {since.UtcDateTime:yyyy-MM-ddTHH:mm:ssZ}");
        var url = $"{Base}/me/mailFolders/inbox/messages?$filter={filter}&$orderby=receivedDateTime asc&$top=50" +
                  "&$select=id,conversationId,subject,from,body,receivedDateTime,internetMessageHeaders";
        var result = new List<MailMessage>();
        while (url != null && result.Count < 200)
        {
            var j = await GetAsync(url, ct, preferText: true);
            foreach (var m in j["value"]!.AsArray())
            {
                var headers = m!["internetMessageHeaders"]?.AsArray()
                    .Select(h => (Name: h!["name"]!.GetValue<string>(), Value: h["value"]!.GetValue<string>()))
                    .ToList() ?? [];
                bool auto = headers.Any(h =>
                    (h.Name.Equals("Auto-Submitted", StringComparison.OrdinalIgnoreCase) && !h.Value.Equals("no", StringComparison.OrdinalIgnoreCase)) ||
                    h.Name.Equals("X-Auto-Response-Suppress", StringComparison.OrdinalIgnoreCase) && h.Value.Contains("All", StringComparison.OrdinalIgnoreCase) ||
                    (h.Name.Equals("Precedence", StringComparison.OrdinalIgnoreCase) && h.Value is "bulk" or "junk" or "list" or "auto_reply"));

                result.Add(new MailMessage(
                    m["id"]!.GetValue<string>(),
                    m["conversationId"]?.GetValue<string>(),
                    m["subject"]?.GetValue<string>() ?? "",
                    m["from"]?["emailAddress"]?["name"]?.GetValue<string>() ?? "",
                    (m["from"]?["emailAddress"]?["address"]?.GetValue<string>() ?? "").ToLowerInvariant(),
                    m["body"]?["content"]?.GetValue<string>() ?? "",
                    m["receivedDateTime"]!.GetValue<DateTimeOffset>(),
                    auto));
            }
            url = j["@odata.nextLink"]?.GetValue<string>();
        }
        return result;
    }

    public Task ReplyToMailAsync(string messageId, string htmlComment, CancellationToken ct) =>
        PostAsync($"{Base}/me/messages/{messageId}/reply", new { comment = htmlComment }, ct);

    public Task ForwardMailAsync(string messageId, IEnumerable<string> to, string htmlComment, CancellationToken ct) =>
        PostAsync($"{Base}/me/messages/{messageId}/forward", new
        {
            comment = htmlComment,
            toRecipients = to.Select(a => new { emailAddress = new { address = a } }),
        }, ct);

    public Task SendMailAsync(IEnumerable<string> to, string subject, string html, CancellationToken ct) =>
        PostAsync($"{Base}/me/sendMail", new
        {
            message = new
            {
                subject,
                body = new { contentType = "HTML", content = html },
                toRecipients = to.Select(a => new { emailAddress = new { address = a } }),
            },
            saveToSentItems = true,
        }, ct);

    public async Task AddCategoryAsync(string messageId, string category, CancellationToken ct)
    {
        var j = await GetAsync($"{Base}/me/messages/{messageId}?$select=categories", ct);
        var cats = j["categories"]?.AsArray().Select(c => c!.GetValue<string>()).ToList() ?? [];
        if (cats.Contains(category)) return;
        cats.Add(category);
        await SendAsync(HttpMethod.Patch, $"{Base}/me/messages/{messageId}", new { categories = cats }, ct);
    }

    // ---------- Teams ----------
    public async Task<List<ChatInfo>> GetRecentChatsAsync(DateTimeOffset since, CancellationToken ct)
    {
        var url = $"{Base}/me/chats?$expand=members&$top=50&$orderby=lastMessagePreview/createdDateTime desc";
        var chats = new List<ChatInfo>();
        var j = await GetAsync(url, ct);
        foreach (var c in j["value"]!.AsArray())
        {
            var updated = c!["lastUpdatedDateTime"]?.GetValue<DateTimeOffset>() ?? DateTimeOffset.MinValue;
            if (updated <= since) continue;
            var members = new Dictionary<string, (string, string)>();
            foreach (var mem in c["members"]?.AsArray() ?? [])
            {
                var uid = mem!["userId"]?.GetValue<string>();
                if (uid == null) continue;
                members[uid] = (mem["displayName"]?.GetValue<string>() ?? "",
                                (mem["email"]?.GetValue<string>() ?? "").ToLowerInvariant());
            }
            chats.Add(new ChatInfo(c["id"]!.GetValue<string>(), c["chatType"]?.GetValue<string>() ?? "", updated, members));
        }
        return chats;
    }

    public async Task<List<ChatMessage>> GetChatMessagesSinceAsync(string chatId, DateTimeOffset since, CancellationToken ct)
    {
        var j = await GetAsync($"{Base}/me/chats/{chatId}/messages?$top=30", ct);
        var list = new List<ChatMessage>();
        foreach (var m in j["value"]!.AsArray())
        {
            if (m!["messageType"]?.GetValue<string>() != "message") continue;
            if (m["deletedDateTime"] is JsonValue) continue;
            var created = m["createdDateTime"]!.GetValue<DateTimeOffset>();
            if (created <= since) continue;
            var user = m["from"]?["user"];
            if (user == null) continue; // bots/apps/system
            list.Add(new ChatMessage(
                m["id"]!.GetValue<string>(), chatId,
                user["id"]?.GetValue<string>() ?? "",
                user["displayName"]?.GetValue<string>() ?? "",
                Html.ToText(m["body"]?["content"]?.GetValue<string>() ?? ""),
                created));
        }
        return list.OrderBy(m => m.Created).ToList();
    }

    public Task SendChatMessageAsync(string chatId, string html, CancellationToken ct) =>
        PostAsync($"{Base}/me/chats/{chatId}/messages", new { body = new { contentType = "html", content = html } }, ct);

    // ---------- HTTP plumbing ----------
    private async Task<JsonNode> GetAsync(string url, CancellationToken ct, bool preferText = false)
    {
        using var req = await BuildAsync(HttpMethod.Get, url, null, ct);
        if (preferText) req.Headers.Add("Prefer", "outlook.body-content-type=\"text\"");
        using var res = await http.SendAsync(req, ct);
        var body = await res.Content.ReadAsStringAsync(ct);
        if (!res.IsSuccessStatusCode) throw new GraphException(res.StatusCode, body);
        return JsonNode.Parse(body)!;
    }

    private Task PostAsync(string url, object payload, CancellationToken ct) => SendAsync(HttpMethod.Post, url, payload, ct);

    private async Task SendAsync(HttpMethod method, string url, object payload, CancellationToken ct)
    {
        using var req = await BuildAsync(method, url, payload, ct);
        using var res = await http.SendAsync(req, ct);
        if (!res.IsSuccessStatusCode)
        {
            var body = await res.Content.ReadAsStringAsync(ct);
            log.LogError("Graph {Method} {Url} failed: {Status} {Body}", method, url, res.StatusCode, body);
            throw new GraphException(res.StatusCode, body);
        }
    }

    private async Task<HttpRequestMessage> BuildAsync(HttpMethod method, string url, object? payload, CancellationToken ct)
    {
        var token = await auth.GetTokenAsync(ct) ?? throw new NotSignedInException();
        var req = new HttpRequestMessage(method, url);
        req.Headers.Authorization = new AuthenticationHeaderValue("Bearer", token);
        if (payload != null)
            req.Content = new StringContent(JsonSerializer.Serialize(payload), Encoding.UTF8, "application/json");
        return req;
    }
}

public class GraphException(System.Net.HttpStatusCode status, string body)
    : Exception($"Graph API error {(int)status}: {Truncate(body)}")
{
    public System.Net.HttpStatusCode Status { get; } = status;
    private static string Truncate(string s) => s.Length > 500 ? s[..500] : s;
}

public class NotSignedInException() : Exception("Not signed in to Microsoft 365. Go to Settings → Connect.");
